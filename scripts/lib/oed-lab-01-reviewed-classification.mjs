export function familyForOrder(order) {
  const family = reviewedFamilies.get(order.orderId);
  if (!family) throw new Error(`Unreviewed laboratory order: ${order.orderId}`);
  return family;
}

export function assertReviewedOrderSet(orders) {
  const ids = new Set(orders.map((order) => order.orderId));
  if (ids.size !== orders.length || ids.size !== reviewedFamilies.size
      || [...reviewedFamilies.keys()].some((id) => !ids.has(id))) {
    throw new Error("Laboratory order IDs differ from the reviewed 86-order set");
  }
}
