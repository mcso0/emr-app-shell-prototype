export type OrderTableGroup = {
  id: string;
  label: string;
  title: string;
  workStatus: OrderGroupWorkStatus;
  assigneeIds: string[];
  rows: Order[];
};

const cloneRowsForGroup = (groupId: string, category: string) =>
  orderRows.map((row) => ({
    ...row,
    id: `${groupId}-${row.id}`,
    category,
  }));

const createOrderRow = ({
  amount = "1",
  assignee = unassignedOrder,
  category,
  days = "7",
  dose,
  doseTiming = "sid",
  dosageForm = "T",
  doctor,
  frequency,
  id,
  medicationGuide = "식전무관",
  name,
  quantity = "7",
  requestedAt,
  route,
  servings = "1",
  status = "요청",
  storage = "실온보관",
  unit = "ea",
  warningMessage,
  workStatus = "대기",
}: {
  amount?: string;
  assignee?: Pick<Order, "assignee" | "assigneeId" | "assigneeInitial">;
  category: string;
  days?: string;
  dose: string;
  doseTiming?: string;
  dosageForm?: string;
  doctor: string;
  frequency: string;
  id: string;
  medicationGuide?: string;
  name: string;
  quantity?: string;
  requestedAt: string;
  route: string;
  servings?: string;
  status?: Order["status"];
  storage?: string;
  unit?: string;
  warningMessage?: string;
  workStatus?: Order["workStatus"];
}): Order => ({
  id,
  category,
  name,
  route,
  dose,
  frequency,
  status,
  requestedAt,
  doctor,
  days,
  doseTiming,
  servings,
  amount,
  unit,
  quantity,
  dosageForm,
  storage,
  medicationGuide,
  ...assignee,
  workStatus,
  warningMessage,
});

const assignedTo = (assigneeId: string): Pick<Order, "assignee" | "assigneeId" | "assigneeInitial"> => {
  const technician = technicianUsers.find((user) => user.id === assigneeId) ?? currentTechnician;

  return {
    assigneeId: technician.id,
    assignee: technician.name,
    assigneeInitial: technician.initial,
  };
};

