function createQuickStatus(tasks: HomeTask[]): HomeQuickStatus[] {
  return [
    { id: "all", label: "내 업무", count: tasks.length },
    { id: "urgent", label: "긴급", count: tasks.filter((task) => task.priority === "urgent").length },
    { id: "dueToday", label: "오늘 마감", count: tasks.filter((task) => task.dueAt).length },
    { id: "overdue", label: "지연", count: tasks.filter((task) => task.status === "overdue").length },
    { id: "roleQueue", label: "미배정 큐", count: tasks.filter((task) => task.assignment === "roleQueue").length },
  ];
}

