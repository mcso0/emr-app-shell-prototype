type PrdFixtureLease = { unmount?: () => void };
let prdFixtureLease: PrdFixtureLease | null = null;
export function preparePrdViewerStory({ epics = false, diagram = false }: { epics?: boolean; diagram?: boolean } = {}) {
  const previousLease = prdFixtureLease;
  const lease: PrdFixtureLease = {};
  prdFixtureLease = lease;
  const keys = [PRD_THEME_STORAGE_KEY, PRD_RECENT_DOCS_STORAGE_KEY];
  const values = keys.map(key => [key, window.localStorage.getItem(key)] as const);
  const previousDark = document.documentElement.classList.contains("dark");
  const previousOverflow = document.body.style.getPropertyValue("overflow");
  const previousOverflowPriority = document.body.style.getPropertyPriority("overflow");
  // Source exposes a readonly tuple for callers; its runtime value is an array.
  // Only this explicitly scoped story fixture replaces display records, keeps
  // original metadata lookup keys, and restores the same array after unmount.
  const fixtureRegistry = prdDocRegistry as unknown as PrdDocEntry[];
  const previousRegistry = fixtureRegistry.slice();
  window.localStorage.setItem(PRD_THEME_STORAGE_KEY, "light");
  window.localStorage.removeItem(PRD_RECENT_DOCS_STORAGE_KEY);
  document.documentElement.classList.remove("dark");
  if (epics) fixtureRegistry.splice(0, fixtureRegistry.length, syntheticEpicIndex, syntheticEpicDetail, syntheticPrdDocs[0]!);
  const previousFetch = globalThis.fetch;
  const previousRender = mermaid.render;
  const pendingRenders = new Set<ReturnType<typeof mermaid.render>>();
  const previousDiagramNodes = new Map<string, Element | null>();
  const trackedRender: typeof mermaid.render = (id, chart, container) => {
    const owned = !container && id.startsWith("clair-docs-mermaid-")
      && (chart === syntheticMermaidChart || chart === invalidSyntheticMermaidChart);
    if (owned) {
      // Mermaid 11.15 creates these temporary body IDs before parsing. The
      // original error path can reject before removing its temporary wrapper.
      for (const nodeId of [id, `d${id}`, `i${id}`]) {
        if (!previousDiagramNodes.has(nodeId)) previousDiagramNodes.set(nodeId, document.getElementById(nodeId));
      }
    }
    const render = previousRender.call(mermaid, id, chart, container);
    if (owned) pendingRenders.add(render);
    return render;
  };
  if (diagram) mermaid.render = trackedRender;
  globalThis.fetch = async (input, init) => {
    const url = new URL(typeof input === "string" ? input : input instanceof URL ? input.href : input.url, window.location.origin);
    if (url.origin === window.location.origin && !url.pathname.startsWith("/api/")) return previousFetch(input, init);
    return Response.json({ ok: false, reason: "no-network-in-synthetic-document-example" }, { status: 503 });
  };
  let cleanupPromise: Promise<void> | undefined;
  return () => {
    if (cleanupPromise) return cleanupPromise;
    cleanupPromise = (async () => {
    // Cancels Header listeners and Mobile's source rAF/240ms closed-scroll cleanup first.
    lease.unmount?.();
    // Keep the original renderer/network boundary until every owned queued
    // render settles. Return its real promise and preserve its SVG/error path.
    await Promise.allSettled([...pendingRenders]);
    for (const [nodeId, previousNode] of previousDiagramNodes) {
      const node = document.getElementById(nodeId);
      if (node && node !== previousNode) node.remove();
    }
    if (diagram && mermaid.render === trackedRender) mermaid.render = previousRender;
    globalThis.fetch = previousFetch;
    if (epics) fixtureRegistry.splice(0, fixtureRegistry.length, ...previousRegistry);
    for (const [key, value] of values) {
      if (value === null) window.localStorage.removeItem(key); else window.localStorage.setItem(key, value);
    }
    document.documentElement.classList.toggle("dark", previousDark);
    if (previousOverflow) document.body.style.setProperty("overflow", previousOverflow, previousOverflowPriority);
    else document.body.style.removeProperty("overflow");
    prdFixtureLease = previousLease;
    })();
    return cleanupPromise;
  };
}

function NavigationCaller({ mobile }: { mobile: boolean }) {
  const [receipt, setReceipt] = useState("초기 링크");
  const observeClick = (event: MouseEvent<HTMLDivElement>) => {
    const link = event.target instanceof Element ? event.target.closest("a") : null;
    if (link) setReceipt(link.getAttribute("href") ?? "");
  };
  return <div className="grid gap-4" onClick={observeClick}>
    {mobile ? <PrdMobileNavigation groups={navigationGroups} activeSlug="product-prd" areaLabel="합성" /> : <div className="h-[400px] w-[300px]"><PrdNavigation groups={navigationGroups} activeSlug="product-prd" /></div>}
    <output aria-label="합성 문서 링크 관찰">{receipt}</output>
  </div>;
}

