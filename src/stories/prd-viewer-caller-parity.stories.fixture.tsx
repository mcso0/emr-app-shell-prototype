function MarkdownServerCaller() {
  const [receipt, setReceipt] = useState("초기 링크");
  return <div className="grid gap-4">
    <article aria-label="합성 서버 Markdown 출력" onClick={event => {
      const link = event.target instanceof Element ? event.target.closest("a") : null;
      if (!link) return;
      // Server HTML has no React hydration. Preserve original href and record only a local receipt.
      event.preventDefault();
      setReceipt(link.getAttribute("href") ?? "");
    }} dangerouslySetInnerHTML={{ __html: serverRenderedSyntheticHtml }} />
    <output aria-label="합성 서버 문서 링크">{receipt}</output>
  </div>;
}

export function PrdViewerCallerExample({ scenario, invalid }: PrdViewerCallerArgs) {
  const [mounted, setMounted] = useState(true);
  useEffect(() => {
    const lease = prdFixtureLease;
    if (!lease) return;
    const unmount = () => flushSync(() => setMounted(false));
    lease.unmount = unmount;
    return () => { if (lease.unmount === unmount) lease.unmount = undefined; };
  }, []);
  if (!mounted) return <output>합성 문서 화면이 해제되었습니다.</output>;
  return <main className={`${styles.prdViewer} min-h-[440px] bg-background p-4 text-foreground`}>
    {scenario === "header" ? <PrdHeaderControls groups={headerGroups} />
      : scenario === "navigation" ? <NavigationCaller mobile={false} />
      : scenario === "mobile" ? <NavigationCaller mobile />
      : scenario === "epics" ? <PlanningCaller />
      : scenario === "markdown" ? <MarkdownServerCaller />
      : <MermaidDiagram chart={invalid ? invalidSyntheticMermaidChart : syntheticMermaidChart} />}
  </main>;
}
